"""Regenerate docs/openapi.json and docs/schema.sql from the code, so they never drift.

    docker compose run --rm --no-deps api python scripts/export_docs.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sqlalchemy.dialects import postgresql  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from app import models  # noqa: E402, F401
from app.db import Base  # noqa: E402
from app.main import app  # noqa: E402

DOCS = ROOT / "docs"
DOCS.mkdir(exist_ok=True)

(DOCS / "openapi.json").write_text(json.dumps(app.openapi(), indent=2), encoding="utf-8")

dialect = postgresql.dialect()
statements = ["-- Generated by scripts/export_docs.py from app/models.py. Do not edit by hand."]
for table in Base.metadata.sorted_tables:
    statements.append(str(CreateTable(table).compile(dialect=dialect)).strip() + ";")
    for index in sorted(table.indexes, key=lambda i: i.name):
        statements.append(str(CreateIndex(index).compile(dialect=dialect)).strip() + ";")
(DOCS / "schema.sql").write_text("\n\n".join(statements) + "\n", encoding="utf-8")

print(f"wrote {DOCS / 'openapi.json'} and {DOCS / 'schema.sql'}")
